// Glossary entries are stored as Markdown definition lists:
//
//   Attempt window
//   : The time bucket in which retries of one invoice run count as the same attempt. See [[Idempotency key]].
//   : Aliases: retry window, window
//   : See also: Idempotency key, Ledger entry
//   : Source: global:7c1e…@3          (imported from the instance-wide glossary, revision 3)
//
// Plain `: text` lines are the definition; the three prefixed lines are optional metadata.
// Shared by the browser (block editor, glossary page) and the server (GLOSSARY.md, MCP tools).
const NOT_TERM = /^(#{1,6}\s|[-*>]\s|```|:\s|R\d+(\s|$)|---+\s*$)/;
const ALIASES = /^(?:aliases|also known as|aka|synonyms):\s*(.*)$/i;
const SEE = /^see also:\s*(.*)$/i;
const ORIGIN = /^source:\s*(global:[\w-]+@\d+)\s*$/i;

export const splitList = (s) => String(s ?? '').split(/[;,]/).map((x) => x.trim()).filter(Boolean);
const clean = (s) => String(s ?? '').replace(/\s*\n\s*/g, ' ').trim();
const item = (s) => clean(s).replace(/[;,]/g, ' ').replace(/\s+/g, ' ');

/** References inside a definition: [[Term]] or [[Term|label]] -> ['Term'] */
export function extractRefs(text) {
  return [...String(text ?? '').matchAll(/\[\[([^\]|\n]+)(?:\|[^\]\n]*)?\]\]/g)].map((m) => m[1].trim()).filter(Boolean);
}

/** The `: …` lines of one entry (without the leading ": ") -> { definition, aliases[], see[], origin } */
export function parseDefLines(lines) {
  const out = { definition: [], aliases: [], see: [], origin: null };
  for (const raw of lines) {
    const l = raw.trim();
    let m;
    if ((m = ALIASES.exec(l))) out.aliases.push(...splitList(m[1]));
    else if ((m = SEE.exec(l))) out.see.push(...splitList(m[1]));
    else if ((m = ORIGIN.exec(l))) out.origin = m[1].toLowerCase();
    else if (l) out.definition.push(l);
  }
  return { ...out, definition: out.definition.join(' ') };
}

export function parseDefinitions(md) {
  const lines = String(md ?? '').replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let fence = false;
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (/^```/.test(l)) { fence = !fence; continue; }
    if (fence || !l.trim() || NOT_TERM.test(l) || !lines[i + 1]?.startsWith(': ')) continue;
    const defs = [];
    while (lines[i + 1]?.startsWith(': ')) defs.push(lines[++i].slice(2));
    const d = parseDefLines(defs);
    out.push({ term: l.trim(), definition: d.definition, aliases: d.aliases, see: d.see, origin: d.origin, refs: extractRefs(d.definition) });
  }
  return out;
}

/** extras: { aliases: string[], see: string[], origin: string|null } */
export function formatDefinition(term, definition, extras = {}) {
  let s = `${item(term)}\n: ${clean(definition)}`;
  const aliases = (extras.aliases ?? []).map(item).filter(Boolean);
  const see = (extras.see ?? []).map(item).filter(Boolean);
  if (aliases.length) s += `\n: Aliases: ${aliases.join(', ')}`;
  if (see.length) s += `\n: See also: ${see.join(', ')}`;
  if (extras.origin) s += `\n: Source: ${extras.origin}`;
  return s;
}

/** entries: [{ term, definition, aliases, see, origin, source }] -> grouped, alphabetical Markdown for the Git repo. */
export function glossaryMarkdown(entries) {
  const byTerm = new Map();
  for (const e of entries) {
    const k = e.term.toLowerCase();
    if (!byTerm.has(k)) byTerm.set(k, { term: e.term, defs: [] });
    byTerm.get(k).defs.push(e);
  }
  const terms = [...byTerm.values()].sort((a, b) => a.term.localeCompare(b.term));
  let md = '# Glossary\n\n_Generated by Specs from the definitions in released specs and documents. Do not edit by hand._\n';
  for (const t of terms) {
    md += `\n## ${t.term}\n\n`;
    for (const d of t.defs) {
      md += `${d.definition}  \n`;
      const see = [...new Set([...(d.see ?? []), ...(d.refs ?? [])])];
      const meta = [d.aliases?.length ? `Also known as: ${d.aliases.join(', ')}` : '', see.length ? `See also: ${see.join(', ')}` : ''].filter(Boolean).join(' · ');
      if (meta) md += `_${meta}_  \n`;
      md += `_Source: ${d.source}${d.origin ? ' (from the global glossary)' : ''}_\n\n`;
    }
    md = md.trimEnd() + '\n';
  }
  return md;
}

/** True when a document says something: ignores blank lines, headings and HTML comments (i.e. an unfilled template is "empty"). */
export function hasContent(md) {
  return String(md ?? '').replace(/<!--[\s\S]*?-->/g, '').split('\n').some((l) => l.trim() && !/^#{1,6}(\s|$)/.test(l.trim()));
}
